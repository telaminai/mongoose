package com.telamin.mongoose.replay.generated;

import com.telamin.fluxtion.runtime.audit.EventLogControlEvent;
import com.telamin.mongoose.MongooseServer;
import com.telamin.mongoose.config.EventFeedConfig;
import com.telamin.mongoose.config.EventProcessorConfig;
import com.telamin.mongoose.config.EventProcessorGroupConfig;
import com.telamin.mongoose.config.MongooseServerConfig;
import com.telamin.mongoose.config.ServiceConfig;
import com.telamin.mongoose.connector.memory.InMemoryEventSource;
import com.telamin.mongoose.service.admin.AdminCommandRegistry;
import com.telamin.mongoose.service.admin.AdminCommandRequest;
import com.telamin.mongoose.service.admin.impl.AdminCommandProcessor;
import org.agrona.concurrent.BusySpinIdleStrategy;
import org.junit.jupiter.api.Test;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Option A proved on a GENERATED processor (spec-replay-recording 3d): AlarmProcessor, generated by the hosted Fluxtion
 * generator from AlarmNodes (design-doc/admin-gen), with audit logging on. A signal-routed admin command gets its own
 * audit record, the node's auditLog writes land in it, and the change propagates to the downstream node within it.
 * A lambda command still works; the invoker brackets it with the processor's audit record, so it has a record of its
 * own too, but its change does not propagate.
 */
class GeneratedAdminAuditTest {

    static List<Object> command(AdminCommandProcessor admin, String name, String... args) {
        List<Object> replies = new CopyOnWriteArrayList<>();
        AdminCommandRequest request = new AdminCommandRequest();
        request.setCommand(name);
        request.setArguments(List.of(args));
        request.setOutput(replies::add);
        request.setErrOutput(o -> replies.add("ERR " + o));
        admin.processAdminCommandRequest(request);
        return replies;
    }

    static void await(List<String> records, int n) throws InterruptedException {
        long deadline = System.nanoTime() + 5_000_000_000L;
        while (records.size() < n && System.nanoTime() < deadline) Thread.sleep(5);
        Thread.sleep(30);
    }

    @Test
    void aSignalCommandIsAuditedAndPropagates_aLambdaIsAuditedButDoesNotPropagate() throws Exception {
        List<String> records = new CopyOnWriteArrayList<>();
        InMemoryEventSource<Object> readings = new InMemoryEventSource<>();
        readings.setName("readings");
        AdminCommandProcessor admin = new AdminCommandProcessor();
        MongooseServerConfig config = MongooseServerConfig.builder()
                .addProcessorGroup(EventProcessorGroupConfig.builder().agentName("processor-agent")
                        .put("alarms", EventProcessorConfig.builder().handler(new AlarmProcessor())
                                .logLevel(EventLogControlEvent.LogLevel.INFO).build()).build())
                .addEventFeed(EventFeedConfig.builder().instance(readings).name("readings").broadcast(true)
                        .agent("readings-agent", new BusySpinIdleStrategy()).build())
                .addService(new ServiceConfig<>(admin, AdminCommandRegistry.class, "adminService"))
                .build();
        MongooseServer server = MongooseServer.bootServer(config, r -> records.add(String.valueOf(r.asCharSequence())));
        List<Object> signalReply, lambdaReply;
        try {
            Thread.sleep(300);
            int start = records.size();
            readings.offer(new AlarmNodes.Reading(12));      await(records, start + 1);
            signalReply = command(admin, "alarm.reset", "DEMO-operator");
            await(records, start + 2);
            readings.offer(new AlarmNodes.Reading(12));      await(records, start + 3);
            lambdaReply = command(admin, "alarm.lambda", "DEMO-operator");
            await(records, start + 4);
            readings.offer(new AlarmNodes.Reading(5));       await(records, start + 5);
            records.subList(0, start).clear();
        } finally {
            server.stop();
        }
        Files.writeString(Path.of("target/generated-admin-audit.yaml"), String.join("\n---\n", records));
        String all = String.join("\n---\n", records);
        assertEquals(5, records.size(), all);

        // option A: the command has its own record, its node's audit lines are in it, and the change propagated to the
        // downstream node within the same cycle
        assertEquals(List.of("alarm cleared"), signalReply);
        String command = records.get(1);
        assertTrue(command.startsWith("eventLogRecord:"), all);
        assertTrue(command.contains("event: Signal") && command.contains("eventFilter: admin:alarm.reset"), command);
        assertTrue(command.contains("- alarmMonitor: { reset: true, resetBy: [DEMO-operator]}"), "the node's audit lines: " + command);
        assertTrue(command.contains("- alarmPublisher: { published: false, changes: 2}"), "propagated downstream: " + command);
        assertEquals(1, records.stream().filter(r -> r.contains("admin:alarm.reset")).count(), "exactly one record names it");
        for (String r : records) assertTrue(r.startsWith("eventLogRecord:"), "every record well formed: " + r);

        // a lambda command still works, and the invoker brackets it with the processor's audit record: a record of its
        // own, its audit line in it, and the next event's record clean (the mangled log is gone). It is not a full
        // cycle: its change marks nothing dirty, so nothing downstream fires
        assertEquals(List.of("lambda cleared"), lambdaReply, "a lambda command still works");
        String lambda = records.get(3);
        assertTrue(lambda.contains("event: AdminCommandEvent")
                && lambda.contains("eventToString: AdminCommandEvent[command=alarm.lambda, args=[DEMO-operator]]"), lambda);
        assertTrue(lambda.contains("- alarmMonitor: { lambdaReset: true, at: "), "its audit line, in its own record: " + lambda);
        // and the command's own instant: the processTime the lambda read is the record's, not the previous event's
        String logTime = lambda.substring(lambda.indexOf("logTime: ") + 9, lambda.indexOf('\n', lambda.indexOf("logTime: ")));
        assertTrue(lambda.contains("at: " + logTime + "}"), "the lambda read the command's instant " + logTime + ": " + lambda);
        String before = records.get(2);
        long previous = Long.parseLong(before.substring(before.indexOf("logTime: ") + 9, before.indexOf('\n', before.indexOf("logTime: "))));
        assertTrue(Long.parseLong(logTime) > previous, "its own instant, later than the previous event's " + previous + ": " + lambda);
        assertFalse(lambda.contains("alarmPublisher"), "no propagation from a lambda: " + lambda);
        String next = records.get(4);
        assertTrue(next.contains("event: Reading") && !next.contains("lambdaReset"), "the next record is its own: " + next);
    }

    @Test
    void theGeneratedSourceIsPublishable() throws Exception {
        // the generator stamps a proprietary copyright header; this public repository commits the source without it,
        // as the analyser does for its DEMO (regenerating and forgetting to strip fails here)
        String source = Files.readString(Path.of("src/test/java/com/telamin/mongoose/replay/generated/AlarmProcessor.java"));
        assertTrue(source.startsWith("package com.telamin.mongoose.replay.generated;"), "no header before the package");
        assertFalse(source.contains("Copyright") || source.contains("All Rights Reserved"), "no generator copyright header");
    }
}
