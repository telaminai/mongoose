package com.telamin.mongoose.control.graph;

import com.telamin.fluxtion.builder.extern.spring.FluxtionSpring;

import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Regenerates the group control processor from its Spring XML design, ahead of time, with the local source generator
 * (fluxtion-generator-core on the classpath), so no API key or network is needed. Run by the {@code regen} profile:
 * {@code mvn -o -Pregen process-classes}. The output is committed; read it to confirm wiring, never edit it.
 */
public final class GenerateControlProcessor {

    public static final String CLASS_NAME = "GroupControlProcessor";
    public static final String PACKAGE = "com.telamin.mongoose.control.generated";

    private GenerateControlProcessor() {
    }

    public static void main(String[] args) throws Exception {
        Path base = Path.of(args.length > 0 ? args[0] : ".").toAbsolutePath();
        Path design = base.resolve("src/main/fluxtion/control/control-processor.xml");
        if (!Files.exists(design)) {
            throw new IllegalStateException("control processor design not found: " + design);
        }
        String sources = base.resolve("src/main/java").toString();
        String resources = base.resolve("src/main/resources").toString();
        FluxtionSpring.compileAot(design, cfg -> {
            cfg.setClassName(CLASS_NAME);
            cfg.setPackageName(PACKAGE);
            cfg.setOutputDirectory(sources);
            cfg.setResourcesOutputDirectory(resources);
            cfg.setWriteSourceToFile(true);
            cfg.setFormatSource(true);
            cfg.setCopySourceToResourcesDirectory(false);   // the source is committed under src/main/java; the GraphML is kept
        });
        replaceHeader(base.resolve("src/main/java").resolve(PACKAGE.replace('.', '/')).resolve(CLASS_NAME + ".java"));
        System.out.println("generated " + PACKAGE + "." + CLASS_NAME + " from " + design);
    }

    /**
     * The generator stamps a proprietary copyright notice on its output; this repository is public under AGPL-3.0,
     * so the generated file carries the project's own licence header instead, plus where it came from.
     */
    static void replaceHeader(Path generated) throws java.io.IOException {
        String source = Files.readString(generated);
        int pkg = source.indexOf("package ");
        if (pkg < 0) throw new IllegalStateException("no package declaration in " + generated);
        String header = """
                /*
                 * SPDX-FileCopyrightText: © 2025 Gregory Higgins <greg.higgins@v12technology.com>
                 * SPDX-License-Identifier: AGPL-3.0-only
                 *
                 * GENERATED by GenerateControlProcessor from src/main/fluxtion/control/control-processor.xml.
                 * Do not edit: change the Spring design or the node classes, then run  mvn -o -Pregen process-classes
                 */
                """;
        Files.writeString(generated, header + source.substring(pkg));
    }
}
